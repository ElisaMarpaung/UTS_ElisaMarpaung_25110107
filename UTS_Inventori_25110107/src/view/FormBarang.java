    private void loadTable() {
        DefaultTableModel model = new DefaultTableModel(
            new String[]{"Kode Barang", "Nama Barang", "Kategori", "Stok"}, 0
        );
        List<Barang> list = barangDAO.getAll();
        for (Barang b : list) {
            model.addRow(new Object[]{
                b.getKodeBarang(), 
                b.getNamaBarang(), 
                b.getKategori(), 
                b.getStok()
            });
        }
        tblBarang.setModel(model);
    }

